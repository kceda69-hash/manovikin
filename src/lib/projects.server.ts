/**
 * Server-only helpers for the MANOVIK project workspace.
 * Kept out of *.functions.ts so the server-fn splitter never drops them.
 */

export type StarterFile = { path: string; content: string; language: string };

export const MAX_FILES_PER_PROJECT = 200;
export const MAX_FILE_BYTES = 200_000;

export function languageForPath(path: string): string {
  const ext = path.split(".").pop()?.toLowerCase() ?? "";
  const map: Record<string, string> = {
    ts: "typescript",
    tsx: "tsx",
    js: "javascript",
    jsx: "jsx",
    json: "json",
    css: "css",
    html: "html",
    md: "markdown",
    py: "python",
    sql: "sql",
    sh: "bash",
    yml: "yaml",
    yaml: "yaml",
  };
  return map[ext] ?? "plaintext";
}

export function normalizePath(input: string): string {
  const cleaned = input
    .trim()
    .replace(/\\/g, "/")
    .replace(/^\/+/, "")
    .replace(/\/{2,}/g, "/");
  if (!cleaned) throw new Error("File path is required");
  if (cleaned.includes("..")) throw new Error("Path traversal is not allowed");
  if (cleaned.length > 240) throw new Error("File path is too long");
  if (!/^[\w./@-]+$/.test(cleaned)) throw new Error("File path has invalid characters");
  return cleaned;
}

